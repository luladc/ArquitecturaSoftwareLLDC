package com.fig.practica2;

/**
 *
 * @author LLDC
 */
public abstract class Animal {
    protected String nombre;

    public Animal() {
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    @Override
    public String toString() {
        return "Animal: " + nombre;
    }
}
